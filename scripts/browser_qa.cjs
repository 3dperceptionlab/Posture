const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1100}});
  const page = await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://api:8080/');
  await page.getByRole('heading',{name:'Bienvenido a POSTURE'}).waitFor();
  await page.screenshot({path:'/results/login.png',fullPage:true});
  await page.locator('[name=username]').fill(process.env.POSTURE_ADMIN_USER);
  await page.locator('[name=password]').fill(process.env.POSTURE_ADMIN_PASSWORD);
  await page.getByRole('button',{name:'Entrar en la plataforma'}).click();
  await page.getByRole('heading',{name:'Tu célula, en perspectiva'}).waitFor();
  await page.getByRole('button',{name:'Simulación de laboratorio',exact:true}).click();
  await page.waitForURL(/#session\/session-/);
  await page.locator('#pose-canvas').waitFor();
  await page.waitForFunction(async()=>{const r=await fetch('/api/v1/stats');const s=await r.json();return s.messages>0&&s.pending===0;},null,{timeout:120000});
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#metric-cards strong')?.textContent!=='—'&&document.querySelector('#metric-cards strong')?.textContent);
  await page.goto('http://api:8080/#overview');
  await page.getByRole('heading',{name:'Tu célula, en perspectiva'}).waitFor();
  await page.waitForFunction(()=>Number(document.querySelector('.stat .number').textContent.replace(/\D/g,''))>0);
  await page.waitForTimeout(800);
  await page.screenshot({path:'/results/overview.png',fullPage:true});
  await page.getByRole('button',{name:'Robot',exact:true}).click();
  await page.getByRole('button',{name:'Persona',exact:true}).click();
  const select=page.locator('#session-select');
  await select.selectOption({index:1});
  await page.locator('#timeline-slider').fill('10');
  await page.getByRole('link',{name:'Operarios y perfiles',exact:true}).click();
  await page.getByRole('button',{name:'Editar perfil',exact:true}).first().click();
  await page.locator('dialog [name=height]').fill('96');
  await page.getByRole('button',{name:'Guardar nueva revisión',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('dialog').open);
  await page.getByRole('link',{name:'Estudios',exact:true}).click();
  await page.getByRole('link',{name:'Abrir estudio'}).first().click();
  await page.locator('.gallery img').first().waitFor();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.gallery img')).every(i=>i.complete&&i.naturalWidth>0));
  await page.screenshot({path:'/results/study.png',fullPage:true});
  await page.getByRole('link',{name:'Autoevaluaciones',exact:true}).click();
  await page.getByRole('heading',{name:'Autoevaluaciones',exact:true}).waitFor();
  await page.getByRole('link',{name:'Sistema',exact:true}).click();
  await page.getByRole('heading',{name:'Estado del sistema'}).waitFor();
  await page.screenshot({path:'/results/system.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://api:8080/#overview');
  await page.getByRole('heading',{name:'Tu célula, en perspectiva'}).waitFor();
  await page.waitForTimeout(500);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  await page.screenshot({path:'/results/mobile.png',fullPage:true});
  const report={browser_errors:errors,mobile_overflow:overflow,checks:['login','demo','metrics','playback','robot-view','profile-edit','study-images','assessments','system','mobile']};
  fs.writeFileSync('/results/browser-report.json',JSON.stringify(report,null,2));
  await browser.close();
  console.log(JSON.stringify(report));
  if(errors.length||overflow)process.exit(1);
})().catch(e=>{console.error(e.message);process.exit(1)});
